export function useOnb() {
  const language = useLanguageStore((s) => s.language);
  return {
    language,
    t: (s: string) => (language === "id" ? (ID[s] ?? s) : s),
    tr: (id: string, en: string) => (language === "id" ? id : en),
  };
}
